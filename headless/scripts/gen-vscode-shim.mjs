// Generates src/vscode/index.ts: one runtime export for every runtime name of the VS Code API.
//
// The names come from @types/vscode, so new API usage by upstream code always resolves.
// Real behaviour lives in ./impl.ts; anything impl does not provide becomes a harmless stub
// (namespaces, functions, classes) or an exact copy (enums, values taken from the typings).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(join(here, "..", "package.json"))
const ts = require("typescript")
const dtsPath = require.resolve("@types/vscode/index.d.ts")
const sf = ts.createSourceFile(dtsPath, readFileSync(dtsPath, "utf8"), ts.ScriptTarget.Latest, true)

const vscodeModule = sf.statements.find(s => ts.isModuleDeclaration(s) && s.name.text === "vscode")
if (!vscodeModule?.body) throw new Error("declare module 'vscode' not found")

const enums = new Map()
const classes = new Set()
const namespaces = new Map()
const values = new Set()
const functions = new Set()

function evalInit(expr, members) {
  if (!expr) return undefined
  if (ts.isNumericLiteral(expr)) return Number(expr.text)
  if (ts.isStringLiteral(expr)) return expr.text
  if (ts.isPrefixUnaryExpression(expr) && expr.operator === ts.SyntaxKind.MinusToken)
    return -evalInit(expr.operand, members)
  if (ts.isParenthesizedExpression(expr)) return evalInit(expr.expression, members)
  if (ts.isIdentifier(expr)) return members.get(expr.text)
  if (ts.isBinaryExpression(expr)) {
    const l = evalInit(expr.left, members)
    const r = evalInit(expr.right, members)
    switch (expr.operatorToken.kind) {
      case ts.SyntaxKind.LessThanLessThanToken:
        return l << r
      case ts.SyntaxKind.BarToken:
        return l | r
      case ts.SyntaxKind.PlusToken:
        return l + r
      case ts.SyntaxKind.AsteriskToken:
        return l * r
    }
  }
  throw new Error(`Unsupported enum initializer: ${expr.getText()}`)
}

for (const st of vscodeModule.body.statements) {
  if (ts.isEnumDeclaration(st)) {
    const members = new Map()
    let next = 0
    for (const m of st.members) {
      const name = m.name.getText()
      const v = m.initializer ? evalInit(m.initializer, members) : next
      members.set(name, v)
      if (typeof v === "number") next = v + 1
    }
    enums.set(st.name.text, members)
  } else if (ts.isClassDeclaration(st) && st.name) classes.add(st.name.text)
  else if (ts.isModuleDeclaration(st) && st.body && ts.isModuleBlock(st.body)) {
    const members = new Set()
    for (const m of st.body.statements) {
      if (ts.isFunctionDeclaration(m) && m.name) members.add(m.name.text)
      else if (ts.isVariableStatement(m))
        for (const d of m.declarationList.declarations) members.add(d.name.getText())
    }
    namespaces.set(st.name.text, members)
  } else if (ts.isVariableStatement(st))
    for (const d of st.declarationList.declarations) values.add(d.name.getText())
  else if (ts.isFunctionDeclaration(st) && st.name) functions.add(st.name.text)
}

const lines = [
  "// GENERATED by scripts/gen-vscode-shim.mjs from @types/vscode — do not edit.",
  "/* eslint-disable */",
  'import * as impl from "./impl"',
  'import { stubClass, stubFunction, stubNamespace, stubValue } from "./stub"',
  "const I = impl as Record<string, any>",
  ""
]
for (const [name, members] of enums) {
  lines.push(`export enum ${name} {`)
  for (const [m, v] of members)
    lines.push(`  ${/^\w+$/.test(m) ? m : JSON.stringify(m)} = ${JSON.stringify(v)},`)
  lines.push("}")
}
for (const name of classes)
  lines.push(`export const ${name}: any = I.${name} ?? stubClass(${JSON.stringify(name)})`)
for (const [name, members] of namespaces)
  lines.push(
    `export const ${name}: any = stubNamespace(${JSON.stringify(name)}, I.${name} ?? {}, ${JSON.stringify([...members])})`
  )
for (const name of values)
  lines.push(`export const ${name}: any = I.${name} ?? stubValue(${JSON.stringify(name)})`)
for (const name of functions)
  lines.push(`export const ${name}: any = I.${name} ?? stubFunction(${JSON.stringify(name)})`)

const out = join(here, "..", "src", "vscode", "index.ts")
mkdirSync(dirname(out), { recursive: true })
// formatted with the repository's prettier config, so upstream's format:check stays green
const prettier = require("prettier")
const options = (await prettier.resolveConfig(out)) ?? {}
writeFileSync(out, await prettier.format(lines.join("\n") + "\n", { ...options, filepath: out }))
console.log(
  `vscode shim: ${enums.size} enums, ${classes.size} classes, ${namespaces.size} namespaces, ${values.size} values, ${functions.size} functions`
)
